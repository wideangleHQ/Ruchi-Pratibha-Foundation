import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { CsrOpportunity } from '@prisma/client';
import { CsrOpportunityWithEvent } from '../csr-opportunities.repository';

type OpportunityEntity = CsrOpportunity | CsrOpportunityWithEvent;

function getEvent(opp: OpportunityEntity): { title: string; eventCode: string } | null {
  return 'event' in opp ? opp.event : null;
}

