    dto.slug = opp.slug;
    dto.title = opp.title;
    dto.opportunityType = opp.opportunityType;
    dto.opportunityStatus = opp.opportunityStatus;
    dto.shortDescription = opp.shortDescription;
    dto.district = opp.district;
    dto.state = opp.state;
    dto.mode = opp.mode;
    dto.registrationCloses = opp.registrationCloses;
    dto.volunteersRequired = opp.volunteersRequired;
    dto.maxApplications = opp.maxApplications;
    dto.isFeatured = opp.isFeatured;
